            yellow "  core.hooksPath already set — skipping"
        else
            git config --global core.hooksPath "$GIT_HOOKS_DIR"
            green "  Set git config --global core.hooksPath $GIT_HOOKS_DIR"
        fi
    else
        yellow "  git-hooks/ directory not found — skipping"
    fi
fi

