#!/usr/bin/env bash
# bootstrap.sh — Set up ~/dotfiles on a fresh machine.
#
# Usage:
#   cd ~/dotfiles && bash bin/bootstrap.sh
#
# Idempotent — safe to re-run. Skips steps that are already done.
# Works on: Windows (Git Bash), Linux (VPS), macOS.

set -euo pipefail

DOTFILES="$HOME/dotfiles"
CLAUDE_DIR="$HOME/.claude"
COPILOT_DIR="$HOME/.copilot"
AGENTS_DIR="$HOME/.agents"
SECRETS_DIR="$DOTFILES/secrets"
VENV_DIR="$SECRETS_DIR/.venv"
CLIENTS_DIR="$DOTFILES/clients"

source "$(dirname "${BASH_SOURCE[0]}")/_lib.sh"

ADOPT_MODE=false
MINIMAL_MODE=false
LEGACY_CHECK_MODE=false
LEGACY_FORCE_MODE=false

for arg in "$@"; do
    case "$arg" in
        --adopt)
            ADOPT_MODE=true
            ;;
        --minimal)
            MINIMAL_MODE=true
            ;;
        --check)
            LEGACY_CHECK_MODE=true
            ;;
        --force)
            LEGACY_FORCE_MODE=true
            ;;
        --help|-h)
            echo "Usage: bash ~/dotfiles/bin/bootstrap.sh [--adopt] [--minimal] [--check] [--force]"
            echo ""
            echo "  (no flags)   Standard setup (idempotent)."
            echo "  --adopt      Merge an existing Claude setup into ctrl+shft with prompts."
            echo "  --minimal    Symlink-focused setup; skips secrets, shell wiring, venv, and supply-chain settings."
            echo "  --check      Legacy compatibility mode; runs validation only and exits."
            echo "  --force      Legacy compatibility alias (no-op; bootstrap already reconciles stale links)."
            exit 0
            ;;
        *)
            red "Unknown argument: $arg"
            red "Run: bash ~/dotfiles/bin/bootstrap.sh --help"
            exit 1
            ;;
    esac
done

if [[ "$LEGACY_CHECK_MODE" == true ]]; then
    yellow "Legacy flag --check detected (compatibility mode)."
    yellow "Running validation only (no bootstrap mutations)."
    _check_fail=0
    if bash "$HOME/dotfiles/bin/validate-env.sh"; then
        :
    else
        _check_fail=1
    fi
    if bash "$HOME/dotfiles/bin/validate-symlinks.sh"; then
        :
    else
        _check_fail=1
    fi
    exit $_check_fail
fi

# ── 1.5. Client scope directory + active context placeholder ─────────────────
echo
green "[1.5/13] Client scope scaffolding"
mkdir -p "$CLIENTS_DIR"
mkdir -p "$DOTFILES/working"
if [[ ! -f "$DOTFILES/working/active-client.md" ]]; then
    cat > "$DOTFILES/working/active-client.md" << 'ACTIVECLIENTEOF'
<!-- Auto-generated by detect-client.sh — no client context active -->
<!-- This file is regenerated on every cd() — do not edit manually -->
ACTIVECLIENTEOF
    green "  Created working/active-client.md placeholder"
else
    yellow "  working/active-client.md already exists — skipping"
fi

if [[ "$LEGACY_FORCE_MODE" == true ]]; then
    yellow "Legacy flag --force detected (compatibility no-op)."
    yellow "bootstrap.sh is idempotent and already repairs stale symlinks/fallback copies."
fi

# ── OS detection ──────────────────────────────────────────────────────────────
OS=$(detect_os)
green "Detected OS: $OS"

# Track failures across all steps
_fail=0

# ── Verify we're inside the dotfiles repo ─────────────────────────────────────
if [[ ! -f "$DOTFILES/CLAUDE.base.md" ]]; then
    red "Error: $DOTFILES/CLAUDE.base.md not found."
    red "Clone the repo first: git clone <repo-url> ~/dotfiles"
    exit 1
fi

if [[ "$ADOPT_MODE" == true ]]; then
    source "$(dirname "${BASH_SOURCE[0]}")/_adopt.sh"
    run_adopt
fi

# ── 1. Create secrets directory and split env files ───────────────────────────
echo
green "[1/13] Secrets directory"
if [[ "$MINIMAL_MODE" == true ]]; then
    yellow "  Skipping secrets setup (--minimal mode)"
else
    mkdir -p "$SECRETS_DIR"

# Migration hint for legacy .env users (must check BEFORE creating new files)
if [[ -f "$SECRETS_DIR/.env" ]] && [[ ! -f "$SECRETS_DIR/.env.agent" ]]; then
    yellow "  MIGRATION: legacy secrets/.env detected. Split into .env.agent + .env.secrets"
    yellow "  See templates: .env.agent.example and .env.secrets.example"
    yellow "  After migrating, delete secrets/.env to complete the transition"
fi

# .env.agent (non-sensitive config — sourced into shell)
if [[ -f "$SECRETS_DIR/.env.agent" ]]; then
    yellow "  secrets/.env.agent already exists — skipping"
else
    if [[ ! -f "$DOTFILES/.env.agent.example" ]]; then
        red "  Error: $DOTFILES/.env.agent.example not found"
        exit 1
    fi
    cp "$DOTFILES/.env.agent.example" "$SECRETS_DIR/.env.agent"
    green "  Created secrets/.env.agent from .env.agent.example"
    yellow "  >>> Fill in non-sensitive config: $SECRETS_DIR/.env.agent"
fi

# .env.secrets (sensitive credentials — process-scoped only)
if [[ -f "$SECRETS_DIR/.env.secrets" ]]; then
    yellow "  secrets/.env.secrets already exists — skipping"
else
    if [[ ! -f "$DOTFILES/.env.secrets.example" ]]; then
        red "  Error: $DOTFILES/.env.secrets.example not found"
        exit 1
    fi
    cp "$DOTFILES/.env.secrets.example" "$SECRETS_DIR/.env.secrets"
    green "  Created secrets/.env.secrets from .env.secrets.example"
    yellow "  >>> Fill in API keys and tokens: $SECRETS_DIR/.env.secrets"
fi
fi

# ── 2. Generate and link CLAUDE.md ─────────────────────────────────────────────
echo
green "[2/13] CLAUDE.md (generated from CLAUDE.base.md + local instructions)"
mkdir -p "$CLAUDE_DIR"
mkdir -p "$DOTFILES/skills/_local"
mkdir -p "$DOTFILES/instructions/_local"

# Generate CLAUDE.md from base + local instruction references
# Write the generated-file header, then append everything after the base header
{
    printf '<!-- GENERATED FILE — do not edit directly.\n'
    printf '     Built by bootstrap.sh from CLAUDE.base.md + local instruction refs.\n'
    printf '     Edit CLAUDE.base.md instead, then run: bash ~/dotfiles/bin/bootstrap.sh -->\n'
    # Skip the original HTML comment block, keep everything after -->
    awk 'BEGIN{skip=1} /-->/{skip=0; next} !skip{print}' "$DOTFILES/CLAUDE.base.md"
} > "$DOTFILES/CLAUDE.md"

_local_instructions=()
_local_conditional=()
if [[ -d "$DOTFILES/instructions/_local" ]]; then
    for f in "$DOTFILES/instructions/_local/"*.instructions.md; do
        [[ -f "$f" ]] || continue
        # Files with `auto-load: false` in frontmatter are task-triggered, not auto-loaded
        if head -20 "$f" | grep -qE '^auto-load:\s*false'; then
            _local_conditional+=("$f")
        else
            _local_instructions+=("$f")
        fi
    done
fi
if [[ ${#_local_instructions[@]} -gt 0 ]]; then
    printf '\n## Local Instructions (auto-generated by bootstrap.sh)\n\n' >> "$DOTFILES/CLAUDE.md"
    for f in "${_local_instructions[@]}"; do
        _fname=$(basename "$f")
        printf '@~/dotfiles/instructions/_local/%s\n' "$_fname" >> "$DOTFILES/CLAUDE.md"
    done
    green "  Generated CLAUDE.md with ${#_local_instructions[@]} local instruction(s)"
else
    green "  Generated CLAUDE.md (no local instructions found)"
fi
if [[ ${#_local_conditional[@]} -gt 0 ]]; then
    printf '\n## Task-Triggered Local Instructions\n\n' >> "$DOTFILES/CLAUDE.md"
    printf 'Read these only when the task matches their description:\n\n' >> "$DOTFILES/CLAUDE.md"
    for f in "${_local_conditional[@]}"; do
        _fname=$(basename "$f")
        # Extract description from frontmatter
        _desc=$(awk '/^description:/{sub(/^description:[[:space:]]*"?/,""); sub(/"?[[:space:]]*$/,""); print; exit}' "$f")
        printf -- '- %s — `~/dotfiles/instructions/_local/%s`\n' "${_desc:-no description}" "$_fname" >> "$DOTFILES/CLAUDE.md"
    done
    green "  Registered ${#_local_conditional[@]} task-triggered local instruction(s)"
fi

# Link or copy to ~/.claude/
if [[ "${ADOPT_SKIP_CLAUDE_MD:-false}" == true ]]; then
    yellow "  Skipping ~/.claude/CLAUDE.md link (--adopt skip)"
else
    if [[ -L "$CLAUDE_DIR/CLAUDE.md" ]]; then
        _target=$(readlink "$CLAUDE_DIR/CLAUDE.md")
        if [[ "$_target" == "$DOTFILES/CLAUDE.md" ]]; then
            yellow "  ~/.claude/CLAUDE.md is already symlinked correctly"
        else
            ln -sf "$DOTFILES/CLAUDE.md" "$CLAUDE_DIR/CLAUDE.md"
            green "  Fixed stale symlink (was $_target)"
        fi
    elif [[ "$OS" == "windows" ]]; then
        cp "$DOTFILES/CLAUDE.md" "$CLAUDE_DIR/CLAUDE.md"
        yellow "  Copied CLAUDE.md to ~/.claude/ (Windows: file symlinks require admin)"
    else
        [[ -f "$CLAUDE_DIR/CLAUDE.md" ]] && yellow "  Replacing regular file with symlink"
        ln -sf "$DOTFILES/CLAUDE.md" "$CLAUDE_DIR/CLAUDE.md"
        green "  Symlinked ~/.claude/CLAUDE.md -> ~/dotfiles/CLAUDE.md"
    fi
fi

# ── 3. Materialise the always-on skill core ───────────────────────────────────
# 🛑 This used to be `ensure_symlink "$DOTFILES/skills" "$CLAUDE_DIR/skills"`, which made
# ~/.claude/skills ONE LINK TO THE WHOLE LIBRARY — so every project loaded all of it.
# Skills are now selected per pod: a pod declares names in pod/skills.txt and a SessionStart
# hook materialises them under <pod>/.claude/skills/. ~/.claude/skills holds only the CORE —
# the handful every project gets whether it asks or not.
#
# 🛑 IT MUST NOT CALL ensure_symlink. That helper does `rm -rf "$target"` when the target is a
# real directory (bin/_lib.sh), so the next routine `ctrl bootstrap` would DELETE the core and
# restore the whole-library symlink — reverting the design silently. This is the reason the
# rewrite had to land in the same change as the swap, not after it.
# Design: cortexos-bakeoff-lab/plans/skill-activation-per-pod/SPEC.md §4/§5.
echo
green "[3/13] Always-on skill core (Claude Code)"
CORE_SKILLS=(ask-codex atomic-commits code-review pr-preflight review-pr-copilot plan-archive)
if [[ "${ADOPT_SKIP_SKILLS:-false}" == true ]]; then
    yellow "  Skipping ~/.claude/skills core (--adopt skip)"
elif [[ -L "$CLAUDE_DIR/skills" ]]; then
    yellow "  ~/.claude/skills is still a symlink to the whole library — leaving it alone."
    yellow "  The per-pod design expects a real directory here; see SPEC.md §5 (the unhook)."
else
    mkdir -p "$CLAUDE_DIR/skills"
    _core_ok=0; _core_bad=0
    for _s in "${CORE_SKILLS[@]}"; do
        if [[ -f "$DOTFILES/skills/$_s/SKILL.md" ]]; then
            ln -sfn "$DOTFILES/skills/$_s" "$CLAUDE_DIR/skills/$_s"
            _core_ok=$(( _core_ok + 1 ))
        else
            red "  core skill missing from the library: $_s"
            _core_bad=$(( _core_bad + 1 ))
        fi
    done
    # Anything in the core directory that is NOT a core member is removed: this directory is
    # generated, and a hand-placed skill here would load in every project silently.
    for _e in "$CLAUDE_DIR/skills"/* "$CLAUDE_DIR/skills"/.[!.]*; do
        [[ -e "$_e" || -L "$_e" ]] || continue
        _b="$(basename "$_e")"
        _keep=0
        for _s in "${CORE_SKILLS[@]}"; do [[ "$_b" == "$_s" ]] && _keep=1; done
        if [[ "$_keep" -eq 0 ]]; then
            yellow "  removing non-core entry from the core directory: $_b"
            rm -rf "$_e"
        fi
    done
    if [[ "$_core_bad" -gt 0 ]]; then
        red "  Core skills linked: $_core_ok — $_core_bad MISSING from the library"
    else
        green "  Core skills linked: $_core_ok"
    fi
    yellow "  Everything else is per-pod: declare it in that pod's pod/skills.txt"
fi

# Report discovered skills
_shared_skills=0
_local_skills=0
for d in "$DOTFILES/skills/"*/; do
    [[ -d "$d" ]] || continue
    _name=$(basename "$d")
    [[ "$_name" == "_local" || "$_name" == "_vendor" ]] && continue
    _shared_skills=$(( _shared_skills + 1 ))
done
if [[ -d "$DOTFILES/skills/_vendor" ]]; then
    yellow "  \"_vendor/ detected. Per ADR-001, move contents to skills/_local/vendor/ then delete skills/_vendor/.\""
fi
if [[ -d "$DOTFILES/skills/_local" ]]; then
    for d in "$DOTFILES/skills/_local/"*/; do
        [[ -d "$d" ]] && [[ -f "$d/SKILL.md" ]] && _local_skills=$(( _local_skills + 1 ))
    done
fi
green "  Skills found: $_shared_skills shared, $_local_skills local"

# ── 4. Symlink ~/.claude/agents/ ─────────────────────────────────────────────
echo
green "[4/13] Agents directory"
mkdir -p "$DOTFILES/agents"
if [[ "${ADOPT_SKIP_AGENTS:-false}" == true ]]; then
    yellow "  Skipping ~/.claude/agents link (--adopt skip)"
else
    ensure_symlink "$DOTFILES/agents" "$CLAUDE_DIR/agents" "~/.claude/agents"
fi

_agents=0
for f in "$DOTFILES/agents/"*.md; do
    [[ -f "$f" ]] && _agents=$(( _agents + 1 ))
done
green "  Agents found: $_agents"

# ── 5. Symlink ~/.claude/rules/ ──────────────────────────────────────────────
echo
green "[5/13] Rules directory"
mkdir -p "$DOTFILES/rules"
if [[ "${ADOPT_SKIP_RULES:-false}" == true ]]; then
    yellow "  Skipping ~/.claude/rules link (--adopt skip)"
else
    ensure_symlink "$DOTFILES/rules" "$CLAUDE_DIR/rules" "~/.claude/rules"
fi

_rules=0
for f in "$DOTFILES/rules/"*.md; do
    [[ -f "$f" ]] && _rules=$(( _rules + 1 ))
done
green "  Rules found: $_rules"

# ── 6. Symlink ~/.claude/commands/ ────────────────────────────────────────────
echo
green "[6/13] Commands directory"
mkdir -p "$DOTFILES/commands"
ensure_symlink "$DOTFILES/commands" "$CLAUDE_DIR/commands" "~/.claude/commands"

_commands=0
for f in "$DOTFILES/commands/"*.md; do
    [[ -f "$f" ]] && _commands=$(( _commands + 1 ))
done
green "  Commands found: $_commands"

# ── 7. Claude Code hooks ──────────────────────────────────────────────────────
echo
green "[7/13] Claude Code hooks"
mkdir -p "$DOTFILES/hooks"
ensure_symlink "$DOTFILES/hooks" "$CLAUDE_DIR/hooks" "~/.claude/hooks"

_hooks=0
for f in "$DOTFILES/hooks/"*.sh; do
    [[ -f "$f" ]] && _hooks=$(( _hooks + 1 ))
done
green "  Hook scripts found: $_hooks"

# Deploy settings.json from dotfiles (source of truth for everything it names)
#
# MERGED, NOT COPIED — the same treatment step 7.5 already gives Gemini, and for
# the same reason. Claude Code writes runtime-managed keys into this file that
# dotfiles deliberately does not carry: `model` is the one that bites, because a
# flat copy silently reverts the operator's chosen model on every bootstrap run.
# That made this whole step unrunnable, which in turn blocked every deliverable
# that has to reach ~/.claude/settings.json (codex-bridge CODEX-OL-02).
#
# Existing file FIRST, dotfiles second: `.[0] * .[1]` lets dotfiles win for every
# key it defines, and leaves keys it does not define untouched. Deploying policy
# still overwrites policy; it just no longer overwrites what it was never the
# source of truth for.
if [[ -f "$DOTFILES/.claude/settings.json" ]]; then
    if [[ -f "$CLAUDE_DIR/settings.json" ]] && command -v jq &>/dev/null; then
        if jq -s '.[0] * .[1]' "$CLAUDE_DIR/settings.json" "$DOTFILES/.claude/settings.json" \
             > "$CLAUDE_DIR/settings.json.tmp" 2>/dev/null; then
            mv "$CLAUDE_DIR/settings.json.tmp" "$CLAUDE_DIR/settings.json"
            green "  Merged dotfiles settings into ~/.claude/settings.json (runtime keys kept)"
        else
            # A failed merge must not fall through to a copy: that is the exact
            # data loss this block exists to prevent.
            rm -f "$CLAUDE_DIR/settings.json.tmp"
            red "  Could not merge ~/.claude/settings.json — left unchanged"
            _fail=1
        fi
    elif [[ -f "$CLAUDE_DIR/settings.json" ]]; then
        yellow "  jq not found — leaving ~/.claude/settings.json unchanged rather than overwriting it"
    else
        cp "$DOTFILES/.claude/settings.json" "$CLAUDE_DIR/settings.json"
        green "  Created ~/.claude/settings.json from dotfiles"
    fi
else
    red "  Missing $DOTFILES/.claude/settings.json — cannot deploy settings"
    _fail=1
fi

# ── 7.5. Gemini CLI safety defaults ──────────────────────────────────────────
echo
green "[7.5/13] Gemini CLI safety defaults"
GEMINI_DIR="$HOME/.gemini"
GEMINI_SAFETY="$DOTFILES/agents/gemini-safety.json"

if [[ -f "$GEMINI_SAFETY" ]]; then
    mkdir -p "$GEMINI_DIR"
    if [[ -f "$GEMINI_DIR/settings.json" ]]; then
        if command -v jq &>/dev/null; then
            jq -s '.[0] * .[1]' "$GEMINI_DIR/settings.json" "$GEMINI_SAFETY" > "$GEMINI_DIR/settings.json.tmp"
            mv "$GEMINI_DIR/settings.json.tmp" "$GEMINI_DIR/settings.json"
            green "  Merged Gemini safety defaults into ~/.gemini/settings.json"
        else
            yellow "  jq not found — cannot merge Gemini safety defaults"
        fi
    else
        cp "$GEMINI_SAFETY" "$GEMINI_DIR/settings.json"
        green "  Created ~/.gemini/settings.json with safety defaults"
    fi
fi

# ── 7.6. Codex CLI safety defaults ───────────────────────────────────────────
echo
green "[7.6/13] Codex CLI safety defaults"
CODEX_DIR="${CODEX_HOME:-$HOME/.codex}"

if [[ -d "$CODEX_DIR" ]] || command -v codex &>/dev/null; then
    mkdir -p "$CODEX_DIR"

    # Ensure [features] codex_hooks = true in config.toml
    if [[ -f "$CODEX_DIR/config.toml" ]]; then
        if ! grep -qF "codex_hooks" "$CODEX_DIR/config.toml"; then
            printf '\n[features]\ncodex_hooks = true\n' >> "$CODEX_DIR/config.toml"
            green "  Added [features] codex_hooks = true to ~/.codex/config.toml"
        else
            yellow "  codex_hooks feature flag already set — skipping"
        fi
    fi

    # Codex hooks require sandshell's hook scripts — suggest if not installed
    if [[ ! -f "$CODEX_DIR/hooks.json" ]]; then
        if command -v sandshell &>/dev/null; then
            yellow "  Run 'sandshell apply codex' to install Codex Pre/PostToolUse hooks"
        else
            yellow "  Install sandshell and run 'sandshell apply codex' for Codex hooks"
        fi
    else
        yellow "  ~/.codex/hooks.json already exists — skipping"
    fi
else
    yellow "  Codex not detected — skipping"
fi

# ── 7.7. Agent Codex home (fenced CODEX_HOME) ────────────────────────────────
echo
green "[7.7/13] Agent Codex home (~/.codex-agent)"
CODEX_AGENT_SRC="$DOTFILES/codex"
CODEX_AGENT_DIR="$HOME/.codex-agent"

if [[ -d "$CODEX_AGENT_SRC" ]]; then
    mkdir -p "$CODEX_AGENT_DIR"

    # Copied, not symlinked: Codex writes session state into CODEX_HOME and
    # appends project trust entries to config.toml. Neither may reach the repo.
    _codex_cfgs=0
    for _f in "$CODEX_AGENT_SRC"/*.toml; do
        [[ -f "$_f" ]] || continue
        cp "$_f" "$CODEX_AGENT_DIR/$(basename "$_f")"
        _codex_cfgs=$(( _codex_cfgs + 1 ))
    done
    green "  Deployed $_codex_cfgs config file(s) to ~/.codex-agent/"

    # auth.json is shared with the interactive home, never copied. Re-linked on
    # every run: a token refresh can replace the symlink with a real file, which
    # would silently fork the credential into a second location.
    if [[ -f "$HOME/.codex/auth.json" ]]; then
        ln -sfn "$HOME/.codex/auth.json" "$CODEX_AGENT_DIR/auth.json"
        green "  Linked ~/.codex-agent/auth.json -> ~/.codex/auth.json"
    else
        yellow "  ~/.codex/auth.json missing — run 'codex login', then re-run"
    fi
else
    yellow "  $CODEX_AGENT_SRC not found — skipping"
fi

# ── 8. Symlink ~/.copilot/skills/ ────────────────────────────────────────────
echo
green "[8/13] Copilot skills directory"
mkdir -p "$COPILOT_DIR"
ensure_symlink "$DOTFILES/skills" "$COPILOT_DIR/skills" "~/.copilot/skills"

# ── 9. Symlink ~/.agents/skills/ ─────────────────────────────────────────────
echo
green "[9/13] Agent framework skills directory"
mkdir -p "$AGENTS_DIR"
ensure_symlink "$DOTFILES/skills" "$AGENTS_DIR/skills" "~/.agents/skills"

# ── 9.5. CLI entry points (ctrl + shft) ──────────────────────────────────────
echo
green "[9.5/13] CLI entry points (ctrl + shft)"

LOCAL_BIN="$HOME/.local/bin"
mkdir -p "$LOCAL_BIN"

# Make scripts executable
chmod +x "$DOTFILES/bin/ctrl" 2>/dev/null || true
chmod +x "$DOTFILES/shft/shft" 2>/dev/null || true

_install_cli() {
    local source="$1" target="$2" label="$3"
    local _os="${OS:-$(detect_os)}"

    if [[ ! -f "$source" ]]; then
        yellow "  $label source not found at $source — skipping"
        return
    fi

    if [[ -L "$target" ]]; then
        local _current
        _current=$(readlink "$target")
        if [[ "$_current" == "$source" ]]; then
            yellow "  $label already symlinked correctly — skipping"
            return
        fi
    fi

    if [[ "$_os" == "windows" ]]; then
        cp "$source" "$target"
        chmod +x "$target" 2>/dev/null || true
        green "  Installed $label (Windows copy)"
    else
        ln -sf "$source" "$target"
        green "  Symlinked $label"
    fi
}

chmod +x "$DOTFILES/bin/ask-codex" 2>/dev/null || true

_install_cli "$DOTFILES/bin/ctrl" "$LOCAL_BIN/ctrl" "ctrl → ~/.local/bin/ctrl"
_install_cli "$DOTFILES/shft/shft" "$LOCAL_BIN/shft" "shft → ~/.local/bin/shft"
# ask-codex reaches Codex through the fenced CODEX_HOME deployed at step 7.7. It
# belongs on PATH because the permission rule that allows it, and denies bare
# codex, matches command text — a wrapper nobody can type by name is not a route.
_install_cli "$DOTFILES/bin/ask-codex" "$LOCAL_BIN/ask-codex" "ask-codex → ~/.local/bin/ask-codex"

# ── 10. Wire up shell ─────────────────────────────────────────────────────────
echo
green "[10/13] Shell integration"

_SHELL_SNIPPET=$(cat << 'SHELLEOF'

## BEGIN ctrlshft

# ── dotfiles/load-secrets ──
[[ -f ~/dotfiles/bin/load-secrets.sh ]] && source ~/dotfiles/bin/load-secrets.sh

# ── dotfiles/cli (ctrl + shft) ──
[[ -d "$HOME/.local/bin" ]] && [[ ":$PATH:" != *":$HOME/.local/bin:"* ]] && export PATH="$HOME/.local/bin:$PATH"

# ── dotfiles/hud ──
[[ -f ~/dotfiles/bin/write-hud-state.sh ]] && source ~/dotfiles/bin/write-hud-state.sh
[[ -x ~/dotfiles/bin/ctrlshft-claude ]] && alias claude='~/dotfiles/bin/ctrlshft-claude'

# ── dotfiles/context-detection ──
_load_context() {
    [[ -f ~/dotfiles/bin/detect-context.sh ]] \
        && source ~/dotfiles/bin/detect-context.sh > /dev/null 2>&1
    [[ -f ~/dotfiles/bin/detect-client.sh ]] \
        && source ~/dotfiles/bin/detect-client.sh > /dev/null 2>&1
}
# cd must NEVER fail because of context detection.
#  - `builtin cd ... && _load_context` returned _load_context's status, so a
#    failing/undefined _load_context made `cd` report failure even though the
#    directory changed — breaking `cd x && y` chains and any `set -e` script.
#  - Non-interactive shells (Claude Code's shell snapshot, some CI) capture the
#    cd wrapper but NOT this underscore-prefixed function, so the call resolved
#    to `command not found: _load_context` on every cd.
# Guard the call and always return cd's own status.
cd() {
    builtin cd "$@" || return
    typeset -f _load_context >/dev/null 2>&1 && _load_context
    return 0
}
typeset -f _load_context >/dev/null 2>&1 && _load_context

## END ctrlshft
SHELLEOF
